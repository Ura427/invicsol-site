/**
 * Writes the list of pickable project photos into a generated module.
 *
 * Built at build time rather than read with fs.readdir when the admin form
 * renders, because on Vercel `public/` is uploaded to the CDN and is not
 * reliably present in the serverless function's filesystem — a picker that
 * works locally and shows an empty grid in production is worse than no picker.
 * The repo already ships one generated module for the same reason
 * (src/shared/ui/logoShapes.ts).
 *
 *   npm run images:manifest
 *
 * It also runs as part of `prebuild`, so a clean checkout cannot deploy a
 * manifest that has drifted from what is actually in the folder.
 */
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const SOURCE_DIRS = ['projects', 'placeholders'] as const;
const IMAGE_PATTERN = /\.(jpe?g|png|webp|avif|svg)$/i;
const OUTPUT = 'src/shared/lib/generated/project-images.ts';

function collect(): string[] {
  return SOURCE_DIRS.flatMap((dir) => {
    let entries: string[];
    try {
      entries = readdirSync(join('public', dir));
    } catch {
      // A missing folder is not a build failure — it just contributes nothing.
      return [];
    }
    return entries
      .filter((name) => IMAGE_PATTERN.test(name))
      // The placeholders folder also holds the station placeholder, which has no
      // business in a project picker.
      .filter((name) => dir !== 'placeholders' || name.startsWith('project-'))
      .sort()
      .map((name) => `/${dir}/${name}`);
  });
}

const paths = collect();

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(
  OUTPUT,
  `/**
 * Generated by scripts/generate-image-manifest.ts — do not edit by hand.
 * Run \`npm run images:manifest\` after adding or removing a photo under
 * public/projects/.
 */
export const PROJECT_IMAGES: readonly string[] = [
${paths.map((path) => `  '${path}',`).join('\n')}
];
`,
  'utf8',
);

console.log(`project-images.ts: ${paths.length} image${paths.length === 1 ? '' : 's'}`);
